import { chromium } from 'playwright';
const url = process.argv[2] || 'http://localhost:3000';
const label = process.argv[3] || 'run';
const b = await chromium.launch({executablePath:'/root/.cache/ms-playwright/chromium_headless_shell-1228/chrome-headless-shell-linux64/chrome-headless-shell'});
const p = await (await b.newContext()).newPage();
const reqs = [];
p.on('request', r => reqs.push(r.url()));
await p.goto(url, { waitUntil: 'networkidle' });
const before = reqs.filter(u => /_next\/static.*\.js/.test(u));
await p.screenshot({ path: `/workspace/.next-maintainer/reproduction-artifacts/playwright/${label}-before-click.png` });
console.log('--- JS requests BEFORE click ---');
before.forEach(u => console.log(u.replace(url, '')));
const html = await p.content();
console.log('preload link for Header in HTML:', /Header/.test(html));
reqs.length = 0;
await p.click('text=Show Header');
await p.waitForTimeout(2000);
console.log('--- JS requests AFTER click ---');
reqs.filter(u => /_next\/static.*\.js/.test(u)).forEach(u => console.log(u.replace(url, '')));
console.log('body:', await p.locator('body').innerText());
await p.screenshot({ path: `/workspace/.next-maintainer/reproduction-artifacts/playwright/${label}-after-click.png` });
await b.close();
