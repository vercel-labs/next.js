import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage()
const art='/workspace/.next-maintainer/reproduction-artifacts/playwright/'
await p.goto('http://localhost:3000/')
await p.waitForTimeout(2000)
console.log('--- clicking Link to /route (prefetch default) ---')
await p.click('text=Link to /route')
await p.waitForTimeout(3000)
await p.screenshot({path: art+'after-link-route.png'})
console.log('url', p.url())
await p.goto('http://localhost:3000/'); await p.waitForTimeout(1500)
console.log('--- clicking Link to /route without prefetch ---')
await p.click('text=Link to /route without prefetch')
await p.waitForTimeout(3000)
console.log('--- redirect to /route via server action ---')
await p.goto('http://localhost:3000/'); await p.waitForTimeout(1500)
await p.click('#redirect-route')
await p.waitForTimeout(3000)
await p.screenshot({path: art+'after-redirect-route.png'})
console.log('--- Link to /page for comparison ---')
await p.goto('http://localhost:3000/'); await p.waitForTimeout(1500)
await p.click('text=Link to /page')
await p.waitForTimeout(3000)
console.log('--- redirect to /page ---')
await p.goto('http://localhost:3000/'); await p.waitForTimeout(1500)
await p.click('#redirect-page')
await p.waitForTimeout(3000)
await b.close()
