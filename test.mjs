import { chromium } from 'playwright'
const OUT = '/workspace/.next-maintainer/reproduction-artifacts/playwright'
const b = await chromium.launch()
const page = await b.newPage()
page.on('console', (m) => console.log('  [browser]', m.type(), m.text()))
await page.goto('http://localhost:3000')
await page.fill('input[name=name]', 'first item')
await page.click('#add')
await page.waitForSelector('#link-1')
console.log('--- added item, navigating to details page')
await page.click('#link-1')
await page.waitForSelector('#delete-push')
await page.screenshot({ path: OUT + '/1-details.png' })
console.log('=== MARKER: clicking "Delete with client-side router.push"')
await page.click('#delete-push')
await page.waitForURL('http://localhost:3000/')
await page.waitForTimeout(3000)
await page.screenshot({ path: OUT + '/2-after-push.png' })
console.log('=== MARKER: done (url =', page.url(), ')')
await b.close()
