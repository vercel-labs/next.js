// Recreates the `.next/types/link.d.ts` file that Next.js 14 (webpack +
// experimental.typedRoutes) leaves in the build directory. Committing `.next`
// directly is not possible, so this script restores that exact artifact.
import { mkdirSync, copyFileSync, writeFileSync } from 'node:fs'

mkdirSync('.next/types', { recursive: true })
copyFileSync('fixtures/next-14-types/link.d.ts', '.next/types/link.d.ts')
writeFileSync('.next/types/package.json', '{"type": "module"}')
console.log('Restored stale .next/types/link.d.ts generated by Next.js 14.2.4')
